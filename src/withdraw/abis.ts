// Only the functions the withdraw page touches. Cellar versions 0.8.15 through 2.6 all expose
// these with ERC4626 signatures.
export const cellarAbi = parseAbi([
  ...somErrors,
  "function balanceOf(address) view returns (uint256)",
  "function decimals() view returns (uint8)",
  "function asset() view returns (address)",
  "function previewRedeem(uint256 shares) view returns (uint256)",
  "function maxRedeem(address owner) view returns (uint256)",
  "function redeem(uint256 shares, address receiver, address owner) returns (uint256)",
  "function allowance(address owner, address spender) view returns (uint256)",
  "function approve(address spender, uint256 amount) returns (bool)",
])

export const erc20Abi = parseAbi([
  "function symbol() view returns (string)",
  "function decimals() view returns (uint8)",
])

// CellarStaking (v0.8.15 and v0.8.21 share this surface). Unstaking requires unbond first,
// then waiting until unbondTimestamp, unless the owner has called emergencyStop (ended == true).
export const stakerAbi = parseAbi([
  ...somErrors,
  "struct UserStake { uint112 amount; uint112 amountWithBoost; uint32 unbondTimestamp; uint112 rewardPerTokenPaid; uint112 rewards; uint8 lock; }",
  "function getUserStakes(address user) view returns (UserStake[])",
  "function ended() view returns (bool)",
  "function paused() view returns (bool)",
  "function unbondAll()",
  "function unstakeAll() returns (uint256[])",
  "function emergencyUnstake()",
])

export const withdrawQueueAbi = parseAbi([
  ...somErrors,
  "struct WithdrawRequest { uint64 deadline; uint88 executionSharePrice; uint96 sharesToWithdraw; bool inSolve; }",
  "function getUserWithdrawRequest(address user, address share) view returns (WithdrawRequest)",
  "function updateWithdrawRequest(address share, WithdrawRequest userRequest)",
])

